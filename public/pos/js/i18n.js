export function setLang(code) {
  current = dict[code] ? code : "ar";
  const meta = LANGS.find((l) => l.code === current);
  document.documentElement.lang = current;
  document.documentElement.dir = meta.dir;
  return current;
}

export function getLang() {
  return current;
}

export function getDir() {
  return LANGS.find((l) => l.code === current).dir;
}

export function getLocale() {
  return LANGS.find((l) => l.code === current).locale;
}

export function t(key, fallback) {
  return dict[current]?.[key] ?? dict.en[key] ?? fallback ?? key;
}

/** Localized entity name helper (nameAr/nameEn/nameFr). */
export function localName(obj) {
  if (!obj) return "—";
  const map = { ar: obj.nameAr, en: obj.nameEn, fr: obj.nameFr };
  return map[current] || obj.nameEn || obj.nameAr || obj.name || "—";
}
